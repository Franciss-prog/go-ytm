func TestStoreSaveLoad(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "cfg")
	s := Store{Dir: dir}
	if _, err := s.Load(); !errors.Is(err, ErrNotConfigured) || s.Exists() {
		t.Fatalf("empty store: %v", err)
	}
	sess := Session{
		Credentials: ytmusic.Credentials{Cookie: "SAPISID=s", UserAgent: "UA", AuthUser: 2},
		Account:     Account{Name: "Jane", Handle: "@jane", ChannelID: "UC1", Source: "firefox", SavedAt: now},
		StreamJar:   StreamJar(jar()),
	}
	if err := s.Save(sess); err != nil {
		t.Fatal(err)
	}
	got, err := s.Load()
	if err != nil {
		t.Fatal(err)
	}
	if got.Credentials != sess.Credentials || got.Account.Slot != 2 || got.Account.Name != "Jane" || got.Account.SchemaVersion != 1 {
		t.Errorf("got %+v", got)
	}
	if runtimeGOOS != "windows" {
		for _, name := range []string{AuthFile, AccountFile, StreamCookiesFile} {
			fi, err := os.Stat(filepath.Join(dir, name))
			if err != nil {
				t.Fatal(err)
			}
			if fi.Mode().Perm() != 0o600 {
				t.Errorf("%s mode %v", name, fi.Mode().Perm())
			}
		}
		if fi, _ := os.Stat(dir); fi.Mode().Perm() != 0o700 {
			t.Errorf("dir mode %v", fi.Mode().Perm())
		}
	}
	entries, _ := os.ReadDir(dir)
	if len(entries) != 3 {
		t.Errorf("leftover temp files: %v", entries)
	}
	if err := os.WriteFile(filepath.Join(dir, AuthFile), []byte(`{"cookie":""}`), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := s.Load(); !errors.Is(err, ErrNotConfigured) {
		t.Errorf("empty cookie: %v", err)
	}
}

// fakeClient answers Account per slot from accounts; missing slots are
// signed out.
type fakeClient struct {
	ytmusic.Client
	creds    ytmusic.Credentials
	accounts map[int]ytmusic.AccountInfo
	err      error
}

func (f fakeClient) Account(context.Context) (ytmusic.AccountInfo, error) {
	if f.err != nil {
		return ytmusic.AccountInfo{}, f.err
	}
	if !strings.Contains(f.creds.Cookie, "__Secure-3PAPISID") {
		return ytmusic.AccountInfo{}, ytmusic.ErrUnauthenticated
	}
	if a, ok := f.accounts[f.creds.AuthUser]; ok {
		return a, nil
	}
	return ytmusic.AccountInfo{}, ytmusic.ErrUnauthenticated
}

func factory(accounts map[int]ytmusic.AccountInfo, err error) ClientFactory {
	return func(c ytmusic.Credentials) ytmusic.Client {
		return fakeClient{creds: c, accounts: accounts, err: err}
	}
}

var (
	jane = ytmusic.AccountInfo{Name: "Jane", Handle: "@jane", ChannelID: "UCjane"}
	band = ytmusic.AccountInfo{Name: "Band", ChannelID: "UCband"}
)

func TestProbeSlots(t *testing.T) {
	ctx := context.Background()
	base := ytmusic.Credentials{Cookie: "__Secure-3PAPISID=x"}
	got, err := ProbeSlots(ctx, factory(map[int]ytmusic.AccountInfo{0: jane, 3: band, 4: jane}, nil), base, 10)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 2 || got[0].Slot != 0 || got[1].Slot != 3 || got[1].Label() != "Band · slot 3" || got[0].Label() != "Jane · @jane · slot 0" {
		t.Errorf("got %+v", got)
	}
	got, err = ProbeSlots(ctx, factory(nil, nil), base, 3)
	if err != nil || len(got) != 0 {
		t.Errorf("signed out: %v %v", got, err)
	}
	netErr := errors.New("dial tcp: no route")
	if _, err := ProbeSlots(ctx, factory(nil, netErr), base, 3); !errors.Is(err, netErr) {
		t.Errorf("network: %v", err)
	}
	cctx, cancel := context.WithCancel(ctx)
	cancel()
	if _, err := ProbeSlots(cctx, factory(nil, nil), base, 3); !errors.Is(err, context.Canceled) {
		t.Errorf("cancelled: %v", err)
	}
}

func TestRenewer(t *testing.T) {
	dir := t.TempDir()
	s := Store{Dir: dir}
	save := func(a Account) {
		t.Helper()
		if err := s.Save(Session{Credentials: ytmusic.Credentials{Cookie: "__Secure-3PAPISID=old", AuthUser: a.Slot}, Account: a}); err != nil {
			t.Fatal(err)
		}
	}
	extract := func(_ context.Context, source string) ([]Cookie, error) {
		if source != "firefox" {
			return nil, errors.New("wrong source")
		}
		return jar(), nil
	}
	r := Renewer{Store: s, Extract: extract, NewClient: factory(map[int]ytmusic.AccountInfo{0: band, 1: jane}, nil), Now: func() time.Time { return now }}

	// The browser reordered accounts: Jane moved from slot 0 to slot 1.
	save(Account{Name: "Jane", ChannelID: "UCjane", Source: "firefox", Slot: 0})
	c, err := r.Renew(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if c.AuthUser != 1 || !strings.Contains(c.Cookie, "__Secure-3PAPISID=s3") {
		t.Errorf("creds = %+v", c)
	}
	if got, _ := s.Load(); got.Account.Slot != 1 || got.Credentials.Cookie != c.Cookie {
		t.Errorf("stored = %+v", got)
	}

	for name, a := range map[string]Account{
		"manual":     {Name: "Jane", ChannelID: "UCjane", Source: "manual"},
		"no channel": {Name: "Jane", Source: "firefox"},
		"gone":       {Name: "Old", ChannelID: "UCgone", Source: "firefox"},
	} {
		save(a)
		if _, err := r.Renew(context.Background()); !errors.Is(err, ErrRenewalUnavailable) {
			t.Errorf("%s: err = %v", name, err)
		}
	}

	save(Account{Name: "Jane", ChannelID: "UCjane", Source: "firefox"})
	dup := r
	dup.NewClient = factory(map[int]ytmusic.AccountInfo{1: jane, 2: {Name: "Jane", ChannelID: "UCjane", Handle: "@other"}}, nil)
	if _, err := dup.Renew(context.Background()); err != nil {
		// Same channel id twice is listed once by ProbeSlots, so slot 1 wins.
		t.Errorf("dedup: %v", err)
	}
}
